GMOS Grating Assembly Checkout ... grating turret indexing check out.

This script will index the grating turret and get it ready to run the
other turret check out scripts.

THE SCRIPT IS A STOP-GAP WHILE THE TURRET LIMIT SWITCHES ARE BROKEN.

Assumptions are ....

        * The GMOS components control database has been loaded.

        * --- THE TURRET MICROSWITCHES ARE BROKEN ---

        * THE GRATING TURRET HAS BEEN MANUALLY POSITIONED AT
          ITS LOWER (A POSITION) HARD LIMIT AND IS ALIGNED
          WITH THE MARKS INDICATED ON THE MASKING TAPE.

        * THE LIFTER *MUST* BE IN A RAISED POSITION.
