GMOS Filter Assembly Checkout ... filter assembly quick check out.
                              ... no UPDATE.

Assumptions are ....

        * The IOC has been depowered and re-started cold, or the filter
          assembly has been reset to its startup state.

        * The GMOS components control database has been loaded.

        * The filter lookup table (flt.lut) exists and contains
          filter IDs valid for its current configuration.

        * There is nothing obstructing the filter wheels.

        If so, it should be safe to check out the filter assembly....

        NOTE: This script will not test the filter barcode readers.
