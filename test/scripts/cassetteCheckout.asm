GMOS Mask Assembly Checkout ... cassette mechanism.

Assumptions are ....

        * The IOC has been depowered and re-started cold, or the
          cassette device has been reset to its startup state.

        * The GMOS components control database has been loaded.

        * There are no cassettes loaded.

        * The extractor is not in a position to cause an interlock
          for the cassette stage (should not be closer than the "clear"
          position.

        * The release device is in the locked position.

        * There is nothing obstructing the cassette carrier.

        If so, it should be safe to move the cassette stage....

