GMOS Translation Assembly Checkout ... translation assembly check out.

Assumptions are ....

        * The IOC has been depowered and re-started cold, or the translation
          assembly has been reset to its startup state.

        * The GMOS components control database has been loaded.

        * The translation lookup table (dta.lut) exists and contains
          a valid calibration.

        * There is nothing obstructing the translation axes.

        If so, it should be safe to check out the translation assembly....
