GMOS Mask Assembly Checkout ... grip device check out.

Assumptions are ....

        * The IOC has been depowered and re-started cold, or the
          grip device has been reset to its startup state.

        * The GMOS components control database has been loaded.

        * There are no cassettes loaded.

        * There is nothing obstructing the gripper arm.

        If so, it should be safe to rotate the gripper....
