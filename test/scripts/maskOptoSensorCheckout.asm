GMOS Mask Opto Sensor Checkout

Assumptions are ....

        * The IOC has been depowered and re-started cold, or the
          mask assembly has been reset into its startup state.
          Prior to rebooting, the mask assembly should have been
          parked at position 2.

        * The GMOS components control database has been loaded.

        * There are NO Cassettes installed, but cassette #2 is
          available to load in its park position. The cassette
          stage should be at park position 2 to allow cassette #2
          to be loaded when prompted for.

        * Cassette #2 is fully loaded with masks.

        * The extractor is clear of the cassette stage, and there
          is nothing that the Mask extractor/gripper could hit
          if moved.

        * The OIWFS probe is not in the path of the Mask 
          extractor/gripper.

        * There are no light sources that may interfere with the
          opto sensors. Position temporary baffles if necessary.

        * The last mask ID in ./data/msk/lut exists in cassette #2
